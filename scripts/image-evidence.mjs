// Builds docs/IMAGE_EVIDENCE.md from the built site (out/): every image file that exists, where it came from, and which pages render it.
import fs from "node:fs";
import path from "node:path";
const root = process.cwd();
const out = path.join(root, "out");
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const pages = walk(out).filter((f) => f.endsWith("index.html"));
const use = {};
for (const f of pages) {
  const html = fs.readFileSync(f, "utf8");
  const route = "/" + path.relative(out, path.dirname(f)).split(path.sep).join("/") + "/";
  for (const m of new Set(html.match(/\/images\/(photo|tools|news)\/[a-z0-9-]+\.webp/g) ?? [])) (use[m.replace(/-sm\.webp$/, ".webp")] ??= new Set()).add(route === "//" || route === "/./" ? "/" : route);
}
const sections = (set) => {
  const r = [...set];
  const g = (p) => r.filter((x) => x.startsWith(p)).length;
  const parts = [];
  if (r.includes("/")) parts.push("home");
  for (const [p, n] of [["/news/", "news"], ["/blog/", "blog"], ["/tools/category/", "category"], ["/tools/", "tool"], ["/best/", "best-of"], ["/compare/", "compare"], ["/credits/", "credits"]]) if (g(p)) parts.push(`${n} (${g(p)})`);
  return parts.join(", ") || "-";
};
const kb = (f) => Math.round(fs.statSync(f).size / 1024);
let md = `# Image evidence (generated ${new Date().toISOString().slice(0, 10)})\n\nGenerated by \`node scripts/image-evidence.mjs\` from the built site. A file is listed as rendered only if its URL appears in the built HTML.\n\n`;
const photoSrc = fs.readFileSync(path.join(root, "src/data/photos.ts"), "utf8");
md += `## Stock photographs (Unsplash License) in public/images/photo/\n\n| File | Size | Photographer | Original page | Rendered on |\n| --- | --- | --- | --- | --- |\n`;
for (const f of fs.readdirSync(path.join(root, "public/images/photo")).filter((x) => !x.includes("-sm"))) {
  const id = f.replace(".webp", "");
  const m = photoSrc.match(new RegExp(`"?${id}"?: \{[^}]*by: "([^"]+)", page: "([^"]+)"`));
  md += `| ${f} | ${kb(path.join(root, "public/images/photo", f))} KB | ${m?.[1]} | ${m?.[2]} | ${sections(use["/images/photo/" + f] ?? new Set())} |\n`;
}
const ti = JSON.parse(fs.readFileSync(path.join(root, "content/tool-images.json"), "utf8"));
md += `\n## Vendor preview images in public/images/tools/ (published by each vendor on its own site; shown with credit)\n\n| File | Size | Image URL | Official page | Fetched | Rendered on |\n| --- | --- | --- | --- | --- | --- |\n`;
for (const [id, e] of Object.entries(ti)) md += `| ${id}.webp | ${kb(path.join(root, "public/images/tools", id + ".webp"))} KB | ${e.imageUrl} | ${e.page} | ${e.fetched} | ${sections(use[`/images/tools/${id}.webp`] ?? new Set())} |\n`;
const ni = JSON.parse(fs.readFileSync(path.join(root, "content/news-images.json"), "utf8"));
md += `\n## News announcement images in public/images/news/ (vendor announcement images, credited)\n\n| Story | Image URL | Credit | Rendered on |\n| --- | --- | --- | --- |\n`;
for (const [slug, e] of Object.entries(ni)) md += `| ${slug} | ${e.imageUrl} | ${e.credit} | ${sections(use[`/images/news/${e.file}.webp`] ?? new Set())} |\n`;
const logos = fs.readdirSync(path.join(root, "public/logos"));
md += `\n## Logos\n\n${logos.length} official logo files in public/logos/, each fetched from the vendor's own site (see docs/ASSETS_REPORT.md for the source URL of every one).\n`;
fs.writeFileSync(path.join(root, "docs/IMAGE_EVIDENCE.md"), md);
console.log("photos", fs.readdirSync(path.join(root, "public/images/photo")).length / 2, "tools", Object.keys(ti).length, "news", Object.keys(ni).length, "logos", logos.length);
